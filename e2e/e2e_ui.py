import os, sys, re
from playwright.sync_api import sync_playwright
B=os.environ.get("SG_URL","http://localhost:5000"); S=os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","sample_data")+"/"
EMAIL=os.environ.get("SG_EMAIL","e2e-user@example.test")
errors=[]; fails=[]
def check(name, cond, extra=""):
    print(("PASS " if cond else "FAIL ")+name+(" -> "+str(extra)[:200] if not cond and extra else ""))
    if not cond: fails.append(name)
def lab(pg,t): return pg.get_by_label(t, exact=True)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ.get("PW_CHROMIUM") or None, args=["--no-sandbox"])
    ctx=b.new_context(viewport={"width":1366,"height":850}); pg=ctx.new_page()
    pg.on("console", lambda m: errors.append(("console",m.text[:200],pg.url)) if m.type=="error" else None)
    pg.on("pageerror", lambda e: errors.append(("pageerror",str(e)[:200],pg.url)))
    pg.on("response", lambda r: errors.append(("http",f"{r.status} {r.url}",pg.url)) if r.status>=500 else None)
    pg.goto(B+"/"); pg.wait_for_load_state("networkidle"); pg.screenshot(path="01_landing.png")
    check("landing renders", pg.get_by_text("StockGhost").count()>0)
    check("demo password never shown", "Demo@12345" not in pg.content())
    # ---- register (weak pw first)
    pg.goto(B+"/register"); pg.wait_for_load_state("networkidle")
    pg.get_by_label("Full name").fill("Priya Sharma"); pg.get_by_label("Company name").fill("Sharma Electronics")
    pg.get_by_label("Business type").select_option("Electronics"); pg.get_by_label("Work email").fill(EMAIL)
    pg.locator("input[type=password]").nth(0).fill("weak"); pg.locator("input[type=password]").nth(1).fill("weak")
    check("weak password disables submit", pg.get_by_role("button", name=re.compile("create|sign up|register", re.I)).is_disabled())
    pg.locator("input[type=password]").nth(0).fill("Strong#Pass1"); pg.locator("input[type=password]").nth(1).fill("Strong#Pass1")
    pg.get_by_role("button", name=re.compile("create|sign up|register", re.I)).click(); pg.wait_for_url(re.compile("onboarding|dashboard"), timeout=8000)
    check("registration logs in and goes to onboarding", "/onboarding" in pg.url, pg.url)
    pg.screenshot(path="02_onboarding.png")
    # ---- onboarding steps
    pg.get_by_role("button", name="Continue").click(); pg.wait_for_timeout(500)
    check("business type step shown", pg.get_by_text("What kind of business").count()>0)
    pg.get_by_role("button", name="Continue").click(); pg.wait_for_timeout(500)
    check("start choice shows both options", pg.get_by_text("Upload my business data").count()>0 and pg.get_by_text("Explore demo data").count()>0)
    pg.get_by_text("Upload my business data").click(); pg.wait_for_timeout(500)
    # ---- upload products
    pg.get_by_text("Product master").first.click()
    pg.set_input_files("input[type=file]", S+"products_sample.csv"); pg.wait_for_selector("text=Map your columns", timeout=8000)
    pg.screenshot(path="03_mapping.png")
    check("auto-mapping filled required fields (continue enabled)", pg.get_by_role("button", name="Validate data").is_enabled())
    check("shows step 5 of 8 on mapping", pg.get_by_text("Step 5 of 8").count()>0)
    pg.get_by_role("button", name="Validate data").click(); pg.wait_for_selector("text=rows detected", timeout=8000)
    pg.screenshot(path="04_validate.png")
    check("validation report shown", pg.get_by_text("valid rows").count()>0)
    pg.get_by_role("button", name=re.compile("^Import \\d+")).click(); pg.wait_for_selector("text=Your analysis is ready", timeout=30000)
    check("import completed -> analysis step", True)
    # ---- add sales
    pg.get_by_role("button", name="Import another file").click(); pg.wait_for_timeout(500)
    pg.get_by_text("Sales data").first.click(); pg.set_input_files("input[type=file]", S+"sales_sample.csv"); pg.wait_for_selector("text=Map your columns", timeout=8000)
    pg.get_by_role("button", name="Validate data").click(); pg.wait_for_selector("text=rows detected", timeout=15000)
    pg.get_by_role("button", name=re.compile("^Import \\d+")).click(); pg.wait_for_selector("text=Your analysis is ready", timeout=40000)
    pg.get_by_role("button", name="Open dashboard").click(); pg.wait_for_url("**/dashboard", timeout=8000); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(1200)
    pg.screenshot(path="05_dashboard.png", full_page=True)
    txt=pg.inner_text("main") if pg.locator("main").count() else pg.inner_text("body")
    check("dashboard shows KPIs from imported data", "Inventory value" in txt or "Total inventory" in txt, txt[:300])
    check("no DEMO badge for real data", pg.get_by_text("DEMO DATA").count()==0)
    check("workspace name shown", pg.get_by_text("Sharma Electronics").count()>0)
    # ---- visit every route
    routes=["/executive","/data-sources","/products","/inventory","/sales","/purchases","/suppliers","/dead-stock","/risk-analysis","/forecasting","/recommendations","/simulator","/copilot","/reports","/notifications","/users","/audit-log","/settings","/data-import"]
    for r in routes:
        n=len(errors); pg.goto(B+r); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(500)
        body=pg.inner_text("body")
        ok_=("Something went wrong" not in body) and len(errors)==n and pg.url.endswith(r)
        check(f"route {r}", ok_, errors[n:] or body[:150])
    pg.goto(B+"/risk-analysis"); pg.wait_for_load_state("networkidle"); pg.screenshot(path="06_risk.png")
    pg.locator("tbody tr").first.click(); pg.wait_for_selector("text=Why this score", timeout=6000); pg.wait_for_timeout(400); pg.screenshot(path="07_risk_detail.png")
    check("risk drawer explains the score", pg.get_by_text("DSRS Score").count()>0)
    pg.keyboard.press("Escape")
    pg.goto(B+"/copilot"); pg.wait_for_load_state("networkidle")
    pg.locator("input, textarea").last.fill("Which products are tying up the most money?"); pg.keyboard.press("Enter"); pg.wait_for_timeout(1500); pg.screenshot(path="08_copilot.png")
    check("copilot answers from workspace data", pg.get_by_text("blocks the most capital").count()>0 or pg.get_by_text("blocked").count()>0, pg.inner_text("body")[-300:])
    # ---- mobile
    m=ctx.new_page(); m.set_viewport_size({"width":390,"height":800}); m.goto(B+"/dashboard"); m.wait_for_load_state("networkidle"); m.wait_for_timeout(800)
    sw=m.evaluate("document.documentElement.scrollWidth"); check("mobile: no horizontal page overflow", sw<=392, sw); m.screenshot(path="09_mobile.png")
    # ---- logout
    pg.goto(B+"/dashboard"); pg.wait_for_load_state("networkidle")
    pg.get_by_role("button", name=re.compile("log ?out|sign out", re.I)).first.click(); pg.wait_for_timeout(1000)
    check("logout -> protected route redirects to login", True)
    pg.goto(B+"/dashboard"); pg.wait_for_timeout(1000); check("dashboard blocked after logout", "/login" in pg.url, pg.url)
    # ---- demo login
    pg.goto(B+"/login"); pg.wait_for_load_state("networkidle")
    pg.get_by_role("button", name=re.compile("demo", re.I)).first.click(); pg.wait_for_url("**/dashboard", timeout=8000); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(1000)
    pg.screenshot(path="10_demo.png")
    check("demo workspace labelled DEMO DATA", pg.get_by_text("DEMO DATA").count()>0)
    b.close()
print("\nJS/HTTP ERRORS:", errors if errors else "none"); print("FAILED:", fails if fails else "none")
